-- Yeli schema for Supabase (Postgres). Safe to run more than once.
CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username CITEXT NOT NULL UNIQUE,
    email CITEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    bio           TEXT NOT NULL DEFAULT '',
    created_at    BIGINT NOT NULL,
    avatar        TEXT NOT NULL DEFAULT '',
    avatar_updated BIGINT NOT NULL DEFAULT 0,
    stream_key    TEXT NOT NULL DEFAULT '',
    name_color    TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS avatars (
    user_id    BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    data       BYTEA NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS chat_messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    text       TEXT NOT NULL,
    created_at BIGINT NOT NULL,
    deleted    BIGINT NOT NULL DEFAULT 0,
    deleted_at BIGINT,
    kind       TEXT NOT NULL DEFAULT 'msg',
    sticker    TEXT NOT NULL DEFAULT '',
    amount     BIGINT NOT NULL DEFAULT 0,
    platform   TEXT NOT NULL DEFAULT '',
    ext_name   TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_chat_channel ON chat_messages(channel_id, id);

CREATE TABLE IF NOT EXISTS follows (
    follower_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    followed_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  BIGINT NOT NULL,
    PRIMARY KEY (follower_id, followed_id)
);

CREATE INDEX IF NOT EXISTS idx_follows_followed ON follows(followed_id);

CREATE TABLE IF NOT EXISTS streams (
    user_id    BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    is_live    BIGINT NOT NULL DEFAULT 0,
    title      TEXT NOT NULL DEFAULT '',
    category   TEXT NOT NULL DEFAULT 'Other',
    started_at BIGINT,
    last_seen  BIGINT,
    mode       TEXT NOT NULL DEFAULT 'p2p',
    ip         TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS destinations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    platform   TEXT NOT NULL,
    name       TEXT NOT NULL DEFAULT '',
    url        TEXT NOT NULL,
    stream_key TEXT NOT NULL,
    enabled    BIGINT NOT NULL DEFAULT 1,
    fmt        TEXT NOT NULL DEFAULT 'original',
    created_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_destinations_user ON destinations(user_id);

CREATE TABLE IF NOT EXISTS bridges (
    user_id        BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    token          TEXT NOT NULL,
    twitch_channel TEXT NOT NULL DEFAULT '',
    twitch_enabled BIGINT NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_bridges_token ON bridges(token);

CREATE TABLE IF NOT EXISTS thumbnails (
    user_id    BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    data       BYTEA NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS viewers (
    peer_id     TEXT PRIMARY KEY,
    streamer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    last_seen   BIGINT NOT NULL,
    viewer_key  TEXT NOT NULL DEFAULT '',
    user_id     BIGINT,
    superseded  BIGINT NOT NULL DEFAULT 0,
    ip          TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_viewers_streamer ON viewers(streamer_id);

CREATE TABLE IF NOT EXISTS signals (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    to_key     TEXT NOT NULL,
    from_key   TEXT NOT NULL,
    kind       TEXT NOT NULL,
    payload    TEXT NOT NULL,
    created_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_signals_to ON signals(to_key, id);

CREATE INDEX IF NOT EXISTS idx_signals_created ON signals(created_at);

CREATE TABLE IF NOT EXISTS wallets (
    user_id BIGINT PRIMARY KEY REFERENCES users(id),
    bought  BIGINT NOT NULL DEFAULT 0 CHECK (bought >= 0)
);

CREATE TABLE IF NOT EXISTS purchases (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id),
    pack_id     TEXT NOT NULL,
    coins       BIGINT NOT NULL,
    gross_cents BIGINT NOT NULL,
    tax_cents   BIGINT NOT NULL,
    fee_cents   BIGINT NOT NULL,
    net_cents   BIGINT NOT NULL,
    provider    TEXT NOT NULL,
    provider_ref TEXT NOT NULL DEFAULT '',
    status      TEXT NOT NULL DEFAULT 'pending',
    created_at  BIGINT NOT NULL,
    paid_at     BIGINT
);

CREATE TABLE IF NOT EXISTS donations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_user  BIGINT NOT NULL REFERENCES users(id),
    to_user    BIGINT NOT NULL REFERENCES users(id),
    coins      BIGINT NOT NULL CHECK (coins > 0),
    message    TEXT NOT NULL DEFAULT '',
    sticker    TEXT NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_donations_to ON donations(to_user, created_at);

CREATE TABLE IF NOT EXISTS payouts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES users(id),
    coins          BIGINT NOT NULL,
    gross_cents    BIGINT NOT NULL,
    withheld_cents BIGINT NOT NULL,
    fee_cents      BIGINT NOT NULL,
    net_cents      BIGINT NOT NULL,
    method         TEXT NOT NULL,
    destination    TEXT NOT NULL,
    status         TEXT NOT NULL DEFAULT 'requested',
    note           TEXT NOT NULL DEFAULT '',
    test           BIGINT NOT NULL DEFAULT 0,
    created_at     BIGINT NOT NULL,
    updated_at     BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS ledger (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id),
    pool       TEXT NOT NULL,
    kind       TEXT NOT NULL,
    coins      BIGINT NOT NULL,
    ref        TEXT NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_ledger_user ON ledger(user_id, id);

CREATE TABLE IF NOT EXISTS upgrade_points (
    user_id BIGINT PRIMARY KEY REFERENCES users(id),
    points  BIGINT NOT NULL DEFAULT 0 CHECK (points >= 0)
);

CREATE TABLE IF NOT EXISTS upgrades (
    user_id BIGINT NOT NULL REFERENCES users(id),
    track   TEXT NOT NULL,
    level   BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id, track)
);

CREATE TABLE IF NOT EXISTS spendings (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id),
    coins      BIGINT NOT NULL CHECK (coins > 0),
    kind       TEXT NOT NULL,
    ref        TEXT NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS commands (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name       TEXT NOT NULL,
    response   TEXT NOT NULL,
    cooldown   BIGINT NOT NULL DEFAULT 5,
    perm       TEXT NOT NULL DEFAULT 'everyone',
    uses       BIGINT NOT NULL DEFAULT 0,
    enabled    BIGINT NOT NULL DEFAULT 1,
    every_min  BIGINT NOT NULL DEFAULT 0,
    last_run   BIGINT NOT NULL DEFAULT 0,
    UNIQUE (channel_id, name)
);

CREATE TABLE IF NOT EXISTS chat_settings (
    channel_id     BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    slow_seconds   BIGINT NOT NULL DEFAULT 0,
    followers_only BIGINT NOT NULL DEFAULT 0,
    block_links    BIGINT NOT NULL DEFAULT 0,
    banned_words   TEXT NOT NULL DEFAULT '',
    caps_percent   BIGINT NOT NULL DEFAULT 0,
    welcome        BIGINT NOT NULL DEFAULT 0,
    welcome_text   TEXT NOT NULL DEFAULT 'Thanks for the follow, {user}!',
    thanks         BIGINT NOT NULL DEFAULT 0,
    thanks_text    TEXT NOT NULL DEFAULT 'Thank you {user} for {amount} Yelis!',
    tts_enabled    BIGINT NOT NULL DEFAULT 0,
    tts_command    TEXT NOT NULL DEFAULT 'say',
    tts_name       BIGINT NOT NULL DEFAULT 1,
    tts_template   TEXT NOT NULL DEFAULT '{user} says: {text}',
    tts_perm       TEXT NOT NULL DEFAULT 'everyone',
    tts_cooldown   BIGINT NOT NULL DEFAULT 30,
    tts_max        BIGINT NOT NULL DEFAULT 120,
    tts_lang       TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS chat_mods (
    channel_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (channel_id, user_id)
);

CREATE TABLE IF NOT EXISTS chat_bans (
    channel_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    until      BIGINT NOT NULL DEFAULT 0,
    reason     TEXT NOT NULL DEFAULT '',
    by_user    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (channel_id, user_id)
);

CREATE TABLE IF NOT EXISTS watch_sessions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    streamer_id    BIGINT NOT NULL,
    viewer_key     TEXT NOT NULL,
    user_id        BIGINT,
    ip             TEXT NOT NULL DEFAULT '',
    started_at     BIGINT NOT NULL,
    last_seen      BIGINT NOT NULL,
    awarded        BIGINT NOT NULL DEFAULT 0,
    stream_started BIGINT NOT NULL DEFAULT 0,
    UNIQUE (streamer_id, viewer_key)
);

CREATE TABLE IF NOT EXISTS free_points (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL,
    viewer_key TEXT NOT NULL,
    created_at BIGINT NOT NULL,
    notified   BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS chest_progress (
    user_id   BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    day       BIGINT NOT NULL,
    seconds   BIGINT NOT NULL DEFAULT 0,
    last_tick BIGINT NOT NULL,
    PRIMARY KEY (user_id, day)
);

CREATE TABLE IF NOT EXISTS chest_opens (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    day       BIGINT NOT NULL,
    kind      TEXT NOT NULL,
    value     TEXT NOT NULL,
    opened_at BIGINT NOT NULL,
    UNIQUE (user_id, day)
);

CREATE TABLE IF NOT EXISTS chest_items (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind    TEXT NOT NULL,
    value   TEXT NOT NULL,
    got_at  BIGINT NOT NULL,
    PRIMARY KEY (user_id, kind, value)
);

CREATE TABLE IF NOT EXISTS events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind       TEXT NOT NULL,
    username   TEXT NOT NULL,
    amount     BIGINT NOT NULL DEFAULT 0,
    sticker    TEXT NOT NULL DEFAULT '',
    message    TEXT NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_events_channel ON events(channel_id, id);

CREATE TABLE IF NOT EXISTS alert_rules (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    event      TEXT NOT NULL,
    min_amount BIGINT NOT NULL DEFAULT 0,
    title      TEXT NOT NULL DEFAULT '',
    image      TEXT NOT NULL DEFAULT '',
    sound      TEXT NOT NULL DEFAULT '',
    volume     BIGINT NOT NULL DEFAULT 80,
    seconds    BIGINT NOT NULL DEFAULT 5,
    enabled    BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS vods (
    id          TEXT PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title       TEXT NOT NULL DEFAULT '',
    description TEXT NOT NULL DEFAULT '',
    category    TEXT NOT NULL DEFAULT 'Other',
    mime        TEXT NOT NULL,
    status      TEXT NOT NULL DEFAULT 'recording',
    size        BIGINT NOT NULL DEFAULT 0,
    chunks      BIGINT NOT NULL DEFAULT 0,
    duration    BIGINT NOT NULL DEFAULT 0,
    started_at  BIGINT NOT NULL,
    ended_at    BIGINT,
    updated_at  BIGINT NOT NULL,
    cover       BYTEA,
    cover_ver   BIGINT NOT NULL DEFAULT 0,
    edited      BIGINT NOT NULL DEFAULT 0,
    
    visibility  TEXT NOT NULL DEFAULT 'public',
    
    source      TEXT NOT NULL DEFAULT 'live',
    live_pct    BIGINT NOT NULL DEFAULT -1,
    project_id  TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_vods_user ON vods(user_id, started_at);

CREATE TABLE IF NOT EXISTS edit_projects (
    id         TEXT PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title      TEXT NOT NULL DEFAULT '',
    data       TEXT NOT NULL,
    duration   DOUBLE PRECISION NOT NULL DEFAULT 0,
    live_pct   BIGINT NOT NULL DEFAULT 0,
    clips      BIGINT NOT NULL DEFAULT 0,
    cover_vod  TEXT NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_edit_projects_user ON edit_projects(user_id, updated_at);

CREATE TABLE IF NOT EXISTS live_likes (
    streamer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  BIGINT NOT NULL,
    PRIMARY KEY (streamer_id, user_id)
);

CREATE TABLE IF NOT EXISTS vod_likes (
    vod_id     TEXT NOT NULL REFERENCES vods(id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (vod_id, user_id)
);

CREATE TABLE IF NOT EXISTS vod_comments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vod_id     TEXT NOT NULL REFERENCES vods(id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    text       TEXT NOT NULL,
    created_at BIGINT NOT NULL,
    
    parent_id  BIGINT REFERENCES vod_comments(id) ON DELETE CASCADE,
    reply_to   BIGINT REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_vod_comments ON vod_comments(vod_id, id);

CREATE TABLE IF NOT EXISTS vod_comment_likes (
    comment_id BIGINT NOT NULL REFERENCES vod_comments(id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (comment_id, user_id)
);

CREATE TABLE IF NOT EXISTS notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind       TEXT NOT NULL,
    actor      TEXT NOT NULL DEFAULT '',
    ref        TEXT NOT NULL DEFAULT '',
    title      TEXT NOT NULL DEFAULT '',
    body       TEXT NOT NULL DEFAULT '',
    amount     BIGINT NOT NULL DEFAULT 0,
    shown      BIGINT NOT NULL DEFAULT 1,
    emailed    BIGINT NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL,
    read_at    BIGINT
);

CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications(user_id, id);

CREATE TABLE IF NOT EXISTS notify_prefs (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind    TEXT NOT NULL,
    in_app  BIGINT NOT NULL DEFAULT 1,
    email   BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id, kind)
);

CREATE TABLE IF NOT EXISTS notify_meta (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    lang    TEXT NOT NULL DEFAULT 'en'
);

CREATE TABLE IF NOT EXISTS assets (
    id         TEXT PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind       TEXT NOT NULL,
    mime       TEXT NOT NULL,
    data       BYTEA NOT NULL,
    created_at BIGINT NOT NULL
);

